#!/usr/bin/env bash
#
# Regenerates Tests/XToolTests/SigningFixtures.swift.
#
# Everything here is throwaway: self-signed certificates with freshly generated keys and
# hand-written provisioning profiles. Nothing is (or could be) valid for Apple's services.
#
# Usage: scripts/generate-signing-fixtures.sh   (needs openssl >= 1.1.1)

set -euo pipefail

cd "$(dirname "$0")/.."
OUT="Tests/XToolTests/SigningFixtures.swift"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

PASSWORD="xtool-test-password"
TEAM="TEAM123456"
BUNDLE_ID="com.example.app"

# make_identity <name> <common name> <team>
make_identity() {
    openssl req -x509 -newkey rsa:2048 -nodes -days 36500 \
        -keyout "$WORK/$1.key" -out "$WORK/$1.pem" \
        -subj "/C=US/O=Xtool Test/OU=$3/CN=$2" 2>/dev/null
    openssl x509 -in "$WORK/$1.pem" -outform DER -out "$WORK/$1.der"
    openssl pkcs12 -export -inkey "$WORK/$1.key" -in "$WORK/$1.pem" \
        -out "$WORK/$1.p12" -passout "pass:$PASSWORD" -name "$2"
}

# make_profile <name> <signer> <cert to embed> <team> <app id suffix> <extra plist keys> <extra entitlements>
#              <expiration date>
make_profile() {
    local name="$1" signer="$2" embedded="$3" team="$4" appid="$5" extra="$6" ents="$7" expires="$8"
    cat > "$WORK/$name.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Name</key><string>xtool $name</string>
    <key>UUID</key><string>00000000-0000-0000-0000-$(printf '%012d' "$RANDOM")</string>
    <key>TeamIdentifier</key><array><string>$team</string></array>
    <key>Platform</key><array><string>iOS</string></array>
    <key>CreationDate</key><date>2024-01-01T00:00:00Z</date>
    <key>ExpirationDate</key><date>$expires</date>
    <key>DeveloperCertificates</key><array><data>$(base64 -w0 < "$WORK/$embedded.der")</data></array>
    $extra
    <key>Entitlements</key>
    <dict>
        <key>application-identifier</key><string>$team.$appid</string>
        <key>com.apple.developer.team-identifier</key><string>$team</string>
        $ents
    </dict>
</dict>
</plist>
PLIST
    openssl cms -sign -nodetach -binary -outform DER \
        -in "$WORK/$name.plist" -signer "$WORK/$signer.pem" -inkey "$WORK/$signer.key" \
        -out "$WORK/$name.mobileprovision"
}

make_identity distribution "Apple Distribution: Xtool Test ($TEAM)" "$TEAM"
make_identity development "Apple Development: Xtool Test (ABCDE12345)" "$TEAM"

FAR="2126-01-01T00:00:00Z"
DEVICES='<key>ProvisionedDevices</key><array><string>00008030-001A2B3C4D5E6F78</string></array>'

STORE_ENTS='<key>get-task-allow</key><false/>
        <key>aps-environment</key><string>production</string>
        <key>beta-reports-active</key><true/>
        <key>com.apple.developer.associated-domains</key><array><string>*</string></array>
        <key>com.apple.security.application-groups</key><array><string>group.com.example.app</string></array>
        <key>keychain-access-groups</key><array><string>'"$TEAM"'.*</string></array>'
ADHOC_ENTS='<key>get-task-allow</key><false/>
        <key>aps-environment</key><string>production</string>
        <key>keychain-access-groups</key><array><string>'"$TEAM"'.*</string></array>'
DEV_ENTS='<key>get-task-allow</key><true/>
        <key>aps-environment</key><string>development</string>
        <key>keychain-access-groups</key><array><string>'"$TEAM"'.*</string></array>'

make_profile appstore distribution distribution "$TEAM" "$BUNDLE_ID" "" "$STORE_ENTS" "$FAR"
make_profile wildcard distribution distribution "$TEAM" "*" "" "$STORE_ENTS" "$FAR"
make_profile adhoc distribution distribution "$TEAM" "$BUNDLE_ID" "$DEVICES" "$ADHOC_ENTS" "$FAR"
make_profile development development development "$TEAM" "$BUNDLE_ID" "$DEVICES" "$DEV_ENTS" "$FAR"
make_profile expired distribution distribution "$TEAM" "$BUNDLE_ID" "" "$STORE_ENTS" "2020-01-01T00:00:00Z"
make_profile otherteam distribution distribution "OTHERTEAM1" "$BUNDLE_ID" "" "$STORE_ENTS" "$FAR"
make_profile othercert distribution development "$TEAM" "$BUNDLE_ID" "" "$STORE_ENTS" "$FAR"
make_profile appextension distribution distribution "$TEAM" "$BUNDLE_ID.widget" "" "$STORE_ENTS" "$FAR"

b64() { base64 -w0 < "$WORK/$1"; }

{
    echo "// Generated by scripts/generate-signing-fixtures.sh. Do not edit."
    echo "// Throwaway self-signed identities and hand-written profiles: no real secret is involved."
    echo
    echo "import Foundation"
    echo
    echo "enum SigningFixtures {"
    echo "    static let teamID = \"$TEAM\""
    echo "    static let bundleID = \"$BUNDLE_ID\""
    echo "    static let p12Password = \"$PASSWORD\""
    echo
    for f in distribution.p12 development.p12 distribution.der \
        appstore.mobileprovision wildcard.mobileprovision adhoc.mobileprovision development.mobileprovision \
        expired.mobileprovision otherteam.mobileprovision othercert.mobileprovision appextension.mobileprovision
    do
        name="$(echo "${f%%.*}" | sed -E 's/^(.)/\L\1/')"
        case "$f" in
            *.p12) name="${name}P12" ;;
            *.der) name="${name}Certificate" ;;
            *.mobileprovision) name="${name}Profile" ;;
        esac
        echo "    // swiftlint:disable:next line_length"
        echo "    static let $name = Data(base64Encoded: \"$(b64 "$f")\")!"
    done
    echo "}"
} > "$OUT"

echo "Wrote $OUT"
